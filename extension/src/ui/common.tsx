export function Modal({ onClose, children }: { onClose: () => void; children: ReactNode }) {
  useEffect(() => {
    const k = (e: KeyboardEvent) => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', k);
    return () => window.removeEventListener('keydown', k);
  }, [onClose]);
  return (
    <div className="scrim" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className="modal" role="dialog">
        {children}
      </div>
    </div>
  );
}

export interface SnackState {
  text: string;
  action?: { label: string; run: () => void };
}
let pushSnack: (s: SnackState) => void = () => {};
export const snack = (s: SnackState) => pushSnack(s);

export function SnackbarHost() {
  const [s, setS] = useState<SnackState | null>(null);
  const timer = useRef<number>();
  pushSnack = (next) => {
    setS(next);
    clearTimeout(timer.current);
    timer.current = window.setTimeout(() => setS(null), 5000);
  };
  if (!s) return null;
  return (
    <div className="snackbar" role="status">
      <span>{s.text}</span>
      {s.action && (
        <button
          onClick={() => {
            s.action!.run();
            setS(null);
          }}
        >
          {s.action.label}
        </button>
      )}
    </div>
  );
}

export function QrImage({ text }: { text: string }) {
  const [url, setUrl] = useState('');
  const [err, setErr] = useState('');
  useEffect(() => {
    QRCode.toDataURL(text, { errorCorrectionLevel: 'L', margin: 1, width: 520 })
      .then(setUrl)
      .catch((e) => setErr(String(e.message ?? e)));
  }, [text]);
  if (err) return <p className="error">QR too large ({err}). Use copy/paste instead.</p>;
  return url ? (
    <div className="qr">
      <img src={url} alt="QR code" />
    </div>
  ) : null;
}

/** Webcam QR scanner (needs camera permission — works in the full-tab app). */
export function QrScanner({ onResult, onCancel }: { onResult: (text: string) => void; onCancel: () => void }) {
  const video = useRef<HTMLVideoElement>(null);
  const [err, setErr] = useState('');
  useEffect(() => {
    let stream: MediaStream | null = null;
    let raf = 0;
    let done = false;
    const canvas = document.createElement('canvas');
    const ctx = canvas.getContext('2d', { willReadFrequently: true })!;
    (async () => {
      try {
        stream = await navigator.mediaDevices.getUserMedia({ video: { facingMode: 'environment' } });
        const v = video.current!;
        v.srcObject = stream;
        await v.play();
        const loop = () => {
          if (done) return;
          if (v.videoWidth) {
            canvas.width = v.videoWidth;
            canvas.height = v.videoHeight;
            ctx.drawImage(v, 0, 0);
            const code = jsQR(ctx.getImageData(0, 0, canvas.width, canvas.height).data, canvas.width, canvas.height);
            if (code?.data) {
              done = true;
              onResult(code.data);
              return;
            }
          }
          raf = requestAnimationFrame(loop);
        };
        loop();
      } catch (e) {
        setErr('Camera unavailable here. Open FingerNotes in a full tab to grant camera access, or paste the code instead.');
      }
    })();
    return () => {
      done = true;
      cancelAnimationFrame(raf);
      stream?.getTracks().forEach((t) => t.stop());
    };
  }, [onResult]);
  return (
    <div className="card-panel" style={{ display: 'grid', gap: 8 }}>
      {err ? <p className="error">{err}</p> : <video ref={video} className="scanner" muted playsInline />}
      <div>
        <button className="btn" onClick={onCancel}>
          Cancel scan
        </button>
      </div>
    </div>
  );
}

export function download(bytes: Uint8Array | Blob, name: string, type: string) {
  const blob = bytes instanceof Blob ? bytes : new Blob([bytes as unknown as ArrayBuffer], { type });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 10_000);
}

